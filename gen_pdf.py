# ── Markdown → Paragraph 内联变换 ──
from xml.sax.saxutils import escape as _xml_escape

def esc(s):
    return _xml_escape(s)

def inline(s):
    s = esc(s)
    s = re.sub(r"`([^`]+)`", r'<font face="Consolas">\1</font>', s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)
    return s

def head_key(text):
    return "h_" + hashlib.md5(text.encode()).hexdigest()[:8]

class TocDoc(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, "bm_text"):
            self.notify("TOCEntry", (flowable.bm_level, flowable.bm_text,
                                     self.page, flowable.bm_key))

def heading(text, style, level):
    key = head_key(text)
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, inline(text)), style)
    p.bm_text = re.sub(r"<[^>]+>", "", inline(text))
    p.bm_level = level
    p.bm_key = key
    return p

def h1_block(text):
    return [CondPageBreak(120), heading(text, S_H1, 0),
            HRFlowable(width="100%", thickness=1.2, color=ACCENT,
                       spaceBefore=0, spaceAfter=10)]

def code_block(lines):
    out = []
    for i in range(0, len(lines), 26):  # 超长分块
        chunk = lines[i:i + 26]
        pre = Preformatted("\n".join(chunk), S_CODE)
        box = Table([[pre]], colWidths=[AVAIL * 0.97])
        box.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("LINEBEFORE", (0, 0), (0, -1), 2, ACCENT),
            ("TOPPADDING", (0, 0), (-1, -1), 7), ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ("LEFTPADDING", (0, 0), (-1, -1), 10), ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]))
        out += [Spacer(1, 4), box, Spacer(1, 6)]
    return out

def md_table(rows):
    heads = [c.strip() for c in rows[0].strip().strip("|").split("|")]
    body = [[c.strip() for c in r.strip().strip("|").split("|")] for r in rows[1:]]
    data = [[Paragraph("<b>%s</b>" % inline(h), S_TH) for h in heads]]
    for r in body:
        data.append([Paragraph(inline(r[k]) if k < len(r) else "", S_TD)
                     for k in range(len(heads))])
    vlen = lambda t: sum(2 if ord(ch) > 0x2E80 else 1 for ch in t)
    weights = [max([vlen(r[k]) if k < len(r) else 1 for r in body] + [vlen(heads[k])])
               for k in range(len(heads))]
    weights = [min(w, 46) for w in weights]
    total = sum(weights)
    widths = [max(w / total * AVAIL * 0.98, 30) for w in weights]
    widths[-1] = max(AVAIL * 0.98 - sum(widths[:-1]), 30)
    t = Table(data, colWidths=widths, hAlign="CENTER", repeatRows=1)
    style = [("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
             ("GRID", (0, 0), (-1, -1), 0.4, BORDER),
             ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
             ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
             ("TOPPADDING", (0, 0), (-1, -1), 4.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5)]
    for i in range(1, len(data)):
        if i % 2 == 0:
            style.append(("BACKGROUND", (0, i), (-1, i), TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    return [Spacer(1, 8), t, Spacer(1, 10)]

def parse_md(md, chapter_title):
    """writeup md → flowables（首个 H1 作为章标题已外置，内部标题降一级）"""
    lines = md.replace("\r\n", "\n").split("\n")
    fences, src, buf, in_f = [], [], [], False
    for ln in lines:
        m = re.match(r"^```(\w*)\s*$", ln)
        if m and not in_f:
            in_f = True; buf = []
        elif ln.strip() == "```" and in_f:
            in_f = False; src.append(("@@F%d@@" % len(fences),)); fences.append(buf[:])
        elif in_f:
            buf.append(ln)
        else:
            src.append((ln,))
    out = h1_block(chapter_title)
    i, first_h1 = 0, True
    while i < len(src):
        raw = src[i][0]
        m = re.match(r"^@@F(\d+)@@$", raw)
        if m:
            out += code_block(fences[int(m.group(1))]); i += 1; continue
        if re.match(r"^#\s+", raw):
            i += 1; continue  # 章标题已用
        if re.match(r"^##\s+", raw):
            h = heading(re.sub(r"^##\s+", "", raw), S_H2, 1)
            out += [CondPageBreak(70), KeepTogether([h])]; i += 1; continue
        if re.match(r"^###\s+", raw):
            h = Paragraph("<b>%s</b>" % inline(re.sub(r"^###\s+", "", raw)), S_H3)
            out += [CondPageBreak(50), h]; i += 1; continue
        if re.match(r"^-{3,}\s*$", raw):
            out.append(HRFlowable(width="30%", thickness=0.6, color=BORDER,
                                  spaceBefore=6, spaceAfter=10, hAlign="LEFT")); i += 1; continue
        if raw.startswith("|"):
            block = []
            while i < len(src) and src[i][0].startswith("|"):
                if not re.match(r"^[\s|:\-]+$", src[i][0].replace("|", "", 1)):
                    block.append(src[i][0])
                i += 1
            out += md_table(block); continue
        if raw.startswith(">"):
            q = []
            while i < len(src) and src[i][0].startswith(">"):
                q.append(src[i][0].lstrip(">").strip()); i += 1
            out.append(Paragraph("<br/>".join(inline(x) for x in q if x), S_QUOTE)); continue
        if re.match(r"^[-*]\s+", raw):
            items = []
            while i < len(src) and re.match(r"^[-*]\s+", src[i][0]):
                items.append(re.sub(r"^[-*]\s+", "", src[i][0])); i += 1
            for x in items:
                out.append(Paragraph(inline(x), S_BULLET, bulletText="•"))
            out.append(Spacer(1, 4)); continue
        if re.match(r"^\d+[.)]\s+", raw):
            items = []
            while i < len(src) and re.match(r"^\d+[.)]\s+", src[i][0]):
                items.append(re.sub(r"^\d+[.)]\s+", "", src[i][0])); i += 1
            for k, x in enumerate(items, 1):
                out.append(Paragraph("%d. %s" % (k, inline(x)), S_BULLET))
            out.append(Spacer(1, 4)); continue
        if raw.strip() == "":
            i += 1; continue
        para = []
        while i < len(src) and src[i][0].strip() and not re.match(
                r"^(#{1,6}\s|[-*]\s|\d+[.)]\s|>|\||-{3,}\s*$|@@F\d+@@)", src[i][0]):
            para.append(src[i][0]); i += 1
        out.append(Paragraph("<br/>".join(inline(x) for x in para), S_BODY))
    return out

def callout(stat, label):
    t = Table([[Paragraph("<b>%s</b>" % stat, S_STAT)], [Paragraph(label, S_STATL)]],
              colWidths=[AVAIL / 4 - 10])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
        ("BOX", (0, 0), (-1, -1), 0.8, BORDER),
        ("TOPPADDING", (0, 0), (-1, 0), 8), ("BOTTOMPADDING", (0, -1), (-1, -1), 8),
        ("TOPPADDING", (0, 1), (-1, 1), 2), ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
    ]))
    return t

class NumberedCanvas(canvas_module.Canvas):
    def __init__(self, *a, **k):
        super().__init__(*a, **k); self._states = []
    def showPage(self):
        self._states.append(dict(self.__dict__)); self._startPage()
    def save(self):
        n = len(self._states)
        for state in self._states:
            self.__dict__.update(state)
            self.setFont("SimHei", 7.2); self.setFillColor(TEXT_MUTED)
            self.drawString(MARGIN, PAGE_H - 34, "Wiz Bug Bounty Masterclass · 9/9 通关复盘")
            self.drawRightString(PAGE_W - MARGIN, PAGE_H - 34, "ruanzhuo × GLM Agent")
            self.setStrokeColor(ACCENT); self.setLineWidth(1.1)
            self.line(MARGIN, PAGE_H - 40, PAGE_W - MARGIN, PAGE_H - 40)
            self.setStrokeColor(BORDER); self.setLineWidth(0.5)
            self.line(MARGIN, 40, PAGE_W - MARGIN, 40)
            self.setFont("SimHei", 7.2)
            self.drawString(MARGIN, 29, "全部敏感内容已脱敏 · 详见仓库 REDACTION.md")
            self.drawRightString(PAGE_W - MARGIN, 29, "第 %d 页" % (n + 1 - len(self._states) + self._states.index(state) + 1))
            super().showPage()
        super().save()

