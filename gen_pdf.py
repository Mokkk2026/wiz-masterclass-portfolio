def merge(cover, body, out):
    from pypdf import PdfReader, PdfWriter
    w = PdfWriter()
    w.add_page(PdfReader(cover).pages[0])
    for p in PdfReader(body).pages:
        w.add_page(p)
    w.add_metadata({"/Title": "Wiz Bug Bounty Masterclass 9/9 通关复盘",
                    "/Author": "ruanzhuo", "/Creator": "ZCode",
                    "/Subject": "GLM Agent 协作通关复盘报告"})
    with open(out, "wb") as f:
        w.write(f)

